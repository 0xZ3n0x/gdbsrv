#pragma once


/**
 * A known NID and the symbol name it was derived from.
 **/
typedef struct gdb_nid {
  char        nid[12];
  const char* name;
} gdb_nid_t;


/**
 * NID-sorted table generated by tools/gen_nidtab.py.
 **/
extern const gdb_nid_t gdb_nidtab[];
extern const unsigned long gdb_nidtab_len;


/**
 * Return the symbol name of an 11-character NID, or NULL if unknown.
 **/
const char* gdb_nid_lookup(const char* nid);
