#!/usr/bin/env python3
# encoding: utf-8
#
# Generate a C source file with a NID-sorted NID -> symbol name table,
# built from the symbol names exported by the PS5 payload SDK stubs.
#
# Usage: gen_nidtab.py [-s SDK] -o OUTFILE

import argparse
import hashlib
import os
import struct
import subprocess
import sys


def nid_encode(sym):
    '''Return the 11-character NID of a symbol name.'''
    # Same algorithm as $PS5_PAYLOAD_SDK/bin/prospero-nid
    charset = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+-'
    salt = b'\x51\x8d\x64\xa6\x35\xde\xd8\xc1\xe6\xb0\x39\xb1\xc3\xe5\x52\x30'
    digest = bytearray(hashlib.sha1(sym.encode('utf-8') + salt).digest())
    value = struct.unpack('>Q', digest[0:8])[0]
    digest[0:8] = struct.pack('<Q', value)

    nid = []
    for i in range(0, 11, 3):
        abc = (digest[i] << 16) | (digest[i+1] << 8) | digest[i+2]
        nid.append(charset[(abc >> 18) & 0x3F])
        nid.append(charset[(abc >> 12) & 0x3F])
        nid.append(charset[(abc >> 6) & 0x3F])
        nid.append(charset[abc & 0x3F])
    return ''.join(nid[:11])


def nm_dynamic(path):
    '''Yield (value, name) of the defined dynamic symbols of an ELF.'''
    try:
        out = subprocess.run(['nm', '-D', '--defined-only', path],
                             capture_output=True, text=True).stdout
    except FileNotFoundError:
        sys.exit('nm (binutils) is required')

    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3:
            continue
        try:
            yield int(parts[0], 16), parts[2]
        except ValueError:
            continue


def build_nid_db(sdk):
    '''Map NID -> name from the symbol names exported by the SDK stubs.'''
    db = {}
    libdir = os.path.join(sdk, 'target', 'lib')
    for fname in sorted(os.listdir(libdir)):
        if not fname.endswith('.so'):
            continue
        for _, name in nm_dynamic(os.path.join(libdir, fname)):
            name = name.split('@')[0]
            db.setdefault(nid_encode(name), name)
    return db


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(
        description='Generate the NID -> name table compiled into gdbsrv')
    ap.add_argument('-s', '--sdk', default=os.environ.get(
        'PS5_PAYLOAD_SDK', '/opt/ps5-payload-sdk'))
    ap.add_argument('-o', '--output', required=True)
    args = ap.parse_args()

    db = build_nid_db(args.sdk)

    with open(args.output, 'w') as f:
        f.write('/* Generated by tools/gen_nidtab.py - do not edit. */\n\n')
        f.write('#include "nidtab.h"\n\n')
        f.write('const gdb_nid_t gdb_nidtab[] = {\n')
        # Sorted with strcmp() ordering so the table can be bsearch()ed.
        for nid in sorted(db, key=lambda s: s.encode()):
            f.write('  {%s, %s},\n' % (c_string(nid), c_string(db[nid])))
        f.write('};\n\n')
        f.write('const unsigned long gdb_nidtab_len = %d;\n' % len(db))


if __name__ == '__main__':
    main()
